# 追加: 数字部分の他年度と揃える細かい既存確認済み箇所（今回のスキャン対象外の年度は含めない）

changed_records = []

def apply_fix(text, old, new):
    if old not in text:
        return text, False
    return text.replace(old, new), True

for q in data:
    qid = q.get('id')
    if qid not in FIXES:
        continue
    rules = FIXES[qid]
    for field in ['text', 'officialExplanation', 'aiExplanation']:
        val = q.get(field)
        if not isinstance(val, str):
            continue
        new_val = val
        for old, new in rules:
            new_val, did = apply_fix(new_val, old, new)
            if did:
                changed_records.append((qid, field, old, new))
        q[field] = new_val
    choices = q.get('choices')
    if isinstance(choices, list):
        for i, c in enumerate(choices):
            if not isinstance(c, str):
                continue
            new_c = c
            for old, new in rules:
                new_c, did = apply_fix(new_c, old, new)
                if did:
                    changed_records.append((qid, f'choices[{i}]', old, new))
            choices[i] = new_c

print(f'Total individual replacements applied: {len(changed_records)}')
for r in changed_records:
    print(' -', r[0], r[1], '::', repr(r[2])[:60], '->', repr(r[3])[:60])

with open(PATH, 'w', encoding='utf-8') as f:
    json.dump(data, f, ensure_ascii=False, indent=2)

